#!/usr/bin/env python3
"""Renders a TrueType font into an anti-aliased VLW font header for LovyanGFX.

The display's built-in fonts are 1-bit bitmaps, so scaling them up gives jagged
edges. A VLW font stores 8-bit coverage per pixel, rendered at the exact size it
is shown, so edges stay smooth.

    python tools/make_vlw.py tools/fonts/InterDisplay-Regular.ttf src/fonts/score_digits.h \\
        --digit-height 98 --chars 0123456789 --name kScoreDigitsVlw

Needs Pillow (pip install pillow).
"""

import argparse
import struct
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


def pixel_size_for(ttf: str, digit_height: int) -> ImageFont.FreeTypeFont:
    """Font whose digit '0' is digit_height pixels tall."""
    size = digit_height
    for _ in range(40):
        font = ImageFont.truetype(ttf, size)
        x0, y0, x1, y1 = font.getbbox("0", anchor="ls")
        h = y1 - y0
        if h == digit_height:
            return font
        size = max(1, round(size * digit_height / h))
    return font


def build(ttf: str, chars: str, digit_height: int) -> tuple[bytes, ImageFont.FreeTypeFont]:
    font = pixel_size_for(ttf, digit_height)
    records, bitmaps = [], []
    ascent = descent = 0
    for ch in sorted(set(chars)):
        x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")  # relative to the baseline origin
        w, h = x1 - x0, y1 - y0
        advance = round(font.getlength(ch))
        if w > 255 or advance > 255:
            raise SystemExit(f"glyph {ch!r} too wide for VLW ({w}px)")
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
        records.append(struct.pack(">7i", ord(ch), h, w, advance, -y0, x0, 0))
        bitmaps.append(img.tobytes())
        ascent, descent = max(ascent, -y0), max(descent, y1)
    header = struct.pack(">6i", len(records), 11, font.size, 0, ascent, descent)
    return header + b"".join(records) + b"".join(bitmaps), font


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("ttf")
    ap.add_argument("out")
    ap.add_argument("--digit-height", type=int, required=True)
    ap.add_argument("--chars", default="0123456789")
    ap.add_argument("--name", default="kVlwFont")
    args = ap.parse_args()

    data, font = build(args.ttf, args.chars, args.digit_height)
    lines = [
        "#pragma once",
        "// Generated by tools/make_vlw.py - do not edit.",
        f"// {Path(args.ttf).name} at {font.size}px (digits {args.digit_height}px tall), chars: {args.chars}",
        "// Inter is licensed under the SIL Open Font License 1.1 (tools/fonts/Inter-LICENSE.txt).",
        "#include <pgmspace.h>",
        "#include <stdint.h>",
        "",
        f"static const uint8_t {args.name}[] PROGMEM = {{",
    ]
    for i in range(0, len(data), 24):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i : i + 24]) + ",")
    lines += ["};", ""]
    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out).write_text("\n".join(lines))
    print(f"{args.out}: {len(data)} bytes, font size {font.size}px")


if __name__ == "__main__":
    main()
